"""Deterministic migration-script generator (iter-13.44).

Produces the three Stage 2 Python scripts without any LLM call:
    1. migrate_old_to_oltp.py — legacy DB → PostgreSQL OLTP (2-pass id-map)
    2. migrate_oltp_to_olap.py — OLTP → star schema (ETL per dim, per fact)
    3. test_migration.py       — pytest row-count + FK + measure-sum checks

All three are templated. Per-project variability comes entirely from:
    • the kb_entities table list (drives source table iteration)
    • the OLTP entity definitions (drives target table iteration)
    • the bus_matrix (drives dim_/fact_ ETL loops)
"""
from __future__ import annotations

import json
import re
from typing import Any, Dict, List, Optional


def _sanitise(name: str) -> str:
    return re.sub(r"[^a-z0-9_]", "_", (name or "").lower()).strip("_") or "_unnamed"


# ----------------------------------------------------------------------------
# Script 1 — Legacy → OLTP
# ----------------------------------------------------------------------------
_OLD_TO_OLTP_TEMPLATE = '''"""migrate_old_to_oltp.py — generated by LAMA (iter-13.44, deterministic).

Migrates data from the legacy {source_tech} database to the new PostgreSQL
OLTP schema. Two-pass strategy:
    Pass 1 — INSERT every legacy row into the corresponding target table,
             generating a UUID PK and recording the id-mapping in a side
             table `_migration_id_map(table_name, legacy_id, new_id)`.
    Pass 2 — Re-walk the source, locate every FK column, look up the new
             UUID for the referenced row, and UPDATE the target FK column.

Env vars:
    SOURCE_DB_HOST, SOURCE_DB_PORT (default 3306),
    SOURCE_DB_USER, SOURCE_DB_PASSWORD, SOURCE_DB_NAME
    TARGET_DB_HOST, TARGET_DB_PORT (default 5432),
    TARGET_DB_USER, TARGET_DB_PASSWORD, TARGET_DB_NAME
"""
from __future__ import annotations

import os
import uuid
import logging
from typing import Any, Dict, List, Tuple

import psycopg2
import psycopg2.extras

logging.basicConfig(level=logging.INFO,
                    format="%(asctime)s [%(levelname)s] %(message)s")
log = logging.getLogger("migrate_old_to_oltp")

BATCH_SIZE = 1000

# (legacy_table, target_table, [(legacy_col, target_col, is_fk, fk_ref_table)])
TABLES: List[Tuple[str, str, List[Tuple[str, str, bool, str]]]] = {tables_literal}

# Reverse-lookup for FK rewiring in pass 2 — built lazily from TABLES.
def _fk_columns(tbl: str) -> List[Tuple[str, str, str]]:
    """Returns [(target_col, ref_table, legacy_col), ...] for one table."""
    out = []
    for legacy_table, target_table, cols in TABLES:
        if target_table != tbl:
            continue
        for legacy_col, target_col, is_fk, ref_table in cols:
            if is_fk and ref_table:
                out.append((target_col, ref_table, legacy_col))
    return out


def _connect_source():
    try:
        import pymysql
    except ImportError as e:
        raise SystemExit("PyMySQL required for source connection: pip install PyMySQL") from e
    return pymysql.connect(
        host=os.environ["SOURCE_DB_HOST"],
        port=int(os.environ.get("SOURCE_DB_PORT", "3306")),
        user=os.environ["SOURCE_DB_USER"],
        password=os.environ["SOURCE_DB_PASSWORD"],
        database=os.environ["SOURCE_DB_NAME"],
        cursorclass=pymysql.cursors.DictCursor,
        charset="utf8mb4",
    )


def _connect_target():
    return psycopg2.connect(
        host=os.environ["TARGET_DB_HOST"],
        port=int(os.environ.get("TARGET_DB_PORT", "5432")),
        user=os.environ["TARGET_DB_USER"],
        password=os.environ["TARGET_DB_PASSWORD"],
        dbname=os.environ["TARGET_DB_NAME"],
    )


def _ensure_id_map(tgt) -> None:
    with tgt.cursor() as cur:
        cur.execute(
            "CREATE TABLE IF NOT EXISTS _migration_id_map ("
            "table_name TEXT NOT NULL, "
            "legacy_id TEXT NOT NULL, "
            "new_id UUID NOT NULL, "
            "PRIMARY KEY (table_name, legacy_id))"
        )
        tgt.commit()


def _record_id_map(tgt, rows: List[Tuple[str, str, str]]) -> None:
    if not rows:
        return
    with tgt.cursor() as cur:
        psycopg2.extras.execute_values(
            cur,
            "INSERT INTO _migration_id_map (table_name, legacy_id, new_id) "
            "VALUES %s ON CONFLICT DO NOTHING",
            rows,
        )
    tgt.commit()


def _lookup_new_id(tgt, ref_table: str, legacy_id: Any) -> str | None:
    with tgt.cursor() as cur:
        cur.execute(
            "SELECT new_id FROM _migration_id_map WHERE table_name=%s AND legacy_id=%s",
            (ref_table, str(legacy_id)),
        )
        row = cur.fetchone()
        return str(row[0]) if row else None


def pass_one(src, tgt) -> None:
    """Insert every row + record id-mapping. FK columns are left NULL here
    and filled in pass 2."""
    for legacy_table, target_table, cols in TABLES:
        log.info("Pass-1 · %s → %s", legacy_table, target_table)
        with src.cursor() as scur:
            scur.execute(f"SELECT * FROM `{{legacy_table}}`")
            while True:
                rows = scur.fetchmany(BATCH_SIZE)
                if not rows:
                    break
                target_cols = ["id"] + [tc for _, tc, is_fk, _ in cols if not is_fk]
                placeholders = ", ".join(["%s"] * len(target_cols))
                col_csv = ", ".join(f'"{{c}}"' for c in target_cols)
                id_map_rows = []
                values = []
                for r in rows:
                    new_id = str(uuid.uuid4())
                    legacy_id = r.get("id") or r.get(f"{{legacy_table}}_id") or next(iter(r.values()))
                    id_map_rows.append((target_table, str(legacy_id), new_id))
                    row_vals = [new_id]
                    for legacy_col, _, is_fk, _ in cols:
                        if is_fk:
                            continue
                        row_vals.append(r.get(legacy_col))
                    values.append(tuple(row_vals))
                with tgt.cursor() as tcur:
                    psycopg2.extras.execute_batch(
                        tcur,
                        f'INSERT INTO "{{target_table}}" ({{col_csv}}) VALUES ({{placeholders}}) ON CONFLICT DO NOTHING',
                        values,
                    )
                tgt.commit()
                _record_id_map(tgt, id_map_rows)


def pass_two(src, tgt) -> None:
    """Rewire FK columns using the id-map populated by pass 1."""
    for legacy_table, target_table, cols in TABLES:
        fk_cols = _fk_columns(target_table)
        if not fk_cols:
            continue
        log.info("Pass-2 · %s FK rewire (%d cols)", target_table, len(fk_cols))
        with src.cursor() as scur:
            scur.execute(f"SELECT * FROM `{{legacy_table}}`")
            while True:
                rows = scur.fetchmany(BATCH_SIZE)
                if not rows:
                    break
                for r in rows:
                    legacy_id = r.get("id") or next(iter(r.values()))
                    new_id = _lookup_new_id(tgt, target_table, legacy_id)
                    if not new_id:
                        continue
                    set_clauses = []
                    params: List[Any] = []
                    for target_col, ref_table, legacy_col in fk_cols:
                        legacy_fk_val = r.get(legacy_col)
                        if legacy_fk_val is None:
                            continue
                        new_fk = _lookup_new_id(tgt, ref_table, legacy_fk_val)
                        if not new_fk:
                            continue
                        set_clauses.append(f'"{{target_col}}" = %s')
                        params.append(new_fk)
                    if not set_clauses:
                        continue
                    params.append(new_id)
                    with tgt.cursor() as tcur:
                        tcur.execute(
                            f'UPDATE "{{target_table}}" SET {{", ".join(set_clauses)}} WHERE "id" = %s',
                            params,
                        )
        tgt.commit()


def main() -> None:
    src = _connect_source()
    tgt = _connect_target()
    try:
        _ensure_id_map(tgt)
        pass_one(src, tgt)
        pass_two(src, tgt)
        log.info("Migration complete: %d tables", len(TABLES))
    finally:
        src.close()
        tgt.close()


if __name__ == "__main__":
    main()
'''



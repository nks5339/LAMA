def _build_tables_literal(entities: List[dict]) -> str:
    rows: List[str] = []
    for ent in entities:
        if (ent.get("type") or "").upper() != "TABLE":
            continue
        tname = _sanitise(ent.get("name") or "")
        if not tname:
            continue
        cols = []
        fk_map = {(_sanitise(f.get("column") or "")): _sanitise(f.get("ref_table") or "")
                  for f in (ent.get("fks") or [])}
        for c in ent.get("columns") or []:
            cn = _sanitise(c.get("name") or "")
            if not cn or cn == "id":
                continue
            ref = fk_map.get(cn, "")
            is_fk = bool(ref)
            cols.append((cn, cn, is_fk, ref))
        rows.append((tname, tname, cols))
    return repr(rows)


def _build_dim_facts_literals(bus_matrix: Dict[str, Any]) -> tuple[str, str]:
    """Return (dims_literal, facts_literal) for the OLTP→OLAP script."""
    dims_payload: List[tuple] = []
    for d in (bus_matrix.get("dimensions") or []):
        dim_table = _sanitise(d.get("name") or "")
        if not dim_table.startswith("dim_"):
            dim_table = "dim_" + dim_table
        src_table = (d.get("source_tables") or [""])[0]
        if not src_table:
            continue
        natural = (d.get("natural_key") or "id")
        attrs = [(_sanitise(a.get("name") or ""), _sanitise(a.get("source_column") or a.get("name") or ""))
                 for a in (d.get("attributes") or []) if a.get("name")]
        dims_payload.append((dim_table, src_table, natural, attrs))

    facts_payload: List[tuple] = []
    matrix = bus_matrix.get("matrix") or {}
    for f in (bus_matrix.get("facts") or []):
        fact_table = _sanitise(f.get("name") or "")
        if not fact_table.startswith("fact_"):
            fact_table = "fact_" + fact_table
        src_table = (f.get("source_tables") or [""])[0]
        if not src_table:
            continue
        date_col = f.get("date_column") or "created_at"
        # Dim joins from matrix row
        row = matrix.get(f.get("name")) or {}
        dim_joins: List[tuple] = []
        for dim_name, used in row.items():
            if not used or dim_name == "dim_date":
                continue
            dim_key = _sanitise(dim_name if dim_name.startswith("dim_") else f"dim_{dim_name}")
            join_col = dim_key.replace("dim_", "") + "_id"
            dim_joins.append((dim_key, dim_key, "natural_key", join_col))
        measures = [(_sanitise(m.get("name") or ""), _sanitise(m.get("source_column") or m.get("name") or ""))
                    for m in (f.get("measures") or []) if m.get("name")]
        facts_payload.append((fact_table, src_table, date_col, dim_joins, measures))

    return repr(dims_payload), repr(facts_payload)


def _build_test_literals(
    entities: List[dict],
    bus_matrix: Dict[str, Any],
) -> tuple[str, str, str]:
    parity: List[tuple] = []
    fk_checks: List[tuple] = []
    for ent in entities:
        if (ent.get("type") or "").upper() != "TABLE":
            continue
        tname = _sanitise(ent.get("name") or "")
        if not tname:
            continue
        parity.append((tname, tname))
        for fk in (ent.get("fks") or []):
            col = _sanitise(fk.get("column") or "")
            ref = _sanitise(fk.get("ref_table") or "")
            if col and ref:
                fk_checks.append((tname, col, ref))

    reconciliations: List[tuple] = []
    for f in (bus_matrix.get("facts") or []):
        fact_table = _sanitise(f.get("name") or "")
        if not fact_table.startswith("fact_"):
            fact_table = "fact_" + fact_table
        src_table = (f.get("source_tables") or [""])[0]
        if not src_table:
            continue
        for m in (f.get("measures") or []):
            mname = _sanitise(m.get("name") or "")
            scol  = _sanitise(m.get("source_column") or m.get("name") or "")
            if mname and scol:
                reconciliations.append((src_table, scol, fact_table, mname))

    return repr(parity), repr(fk_checks), repr(reconciliations)


def generate_old_to_oltp(entities: List[dict], source_tech: str = "MySQL") -> str:
    return _OLD_TO_OLTP_TEMPLATE.format(
        source_tech=source_tech,
        tables_literal=_build_tables_literal(entities),
    )


def generate_oltp_to_olap(bus_matrix: Dict[str, Any]) -> str:
    dims_lit, facts_lit = _build_dim_facts_literals(bus_matrix)
    return _OLTP_TO_OLAP_TEMPLATE.format(
        dims_literal=dims_lit,
        facts_literal=facts_lit,
    )


def generate_test_migration(
    entities: List[dict],
    bus_matrix: Dict[str, Any],
) -> str:
    parity_lit, fk_lit, recon_lit = _build_test_literals(entities, bus_matrix)
    return _TEST_MIGRATION_TEMPLATE.format(
        parity_literal=parity_lit,
        fk_checks_literal=fk_lit,
        reconciliations_literal=recon_lit,
    )


def generate_all(
    entities: List[dict],
    bus_matrix: Dict[str, Any],
    source_tech: str = "MySQL",
) -> Dict[str, str]:
    """Convenience: return all 3 scripts keyed by artifact type."""
    return {
        "migrate_old_to_oltp":  generate_old_to_oltp(entities, source_tech),
        "migrate_oltp_to_olap": generate_oltp_to_olap(bus_matrix),
        "test_migration":       generate_test_migration(entities, bus_matrix),
    }


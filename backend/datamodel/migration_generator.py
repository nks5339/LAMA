_OLTP_TO_OLAP_TEMPLATE = '''"""migrate_oltp_to_olap.py — generated by LAMA (iter-13.44, deterministic).

ETL from the OLTP schema into the OLAP star schema:
    • For each dimension → INSERT INTO dim_<x> SELECT <natural_key>, attrs FROM <source_oltp>.
    • For each fact      → INSERT INTO fact_<x> SELECT date_key, dim_keys, measures
                           FROM <source_oltp> joined to the relevant OLTP tables.
"""
from __future__ import annotations

import os
import logging
from datetime import date, timedelta

import psycopg2

logging.basicConfig(level=logging.INFO,
                    format="%(asctime)s [%(levelname)s] %(message)s")
log = logging.getLogger("migrate_oltp_to_olap")


def _connect():
    return psycopg2.connect(
        host=os.environ["TARGET_DB_HOST"],
        port=int(os.environ.get("TARGET_DB_PORT", "5432")),
        user=os.environ["TARGET_DB_USER"],
        password=os.environ["TARGET_DB_PASSWORD"],
        dbname=os.environ["TARGET_DB_NAME"],
    )


def populate_dim_date(conn) -> None:
    """Populate dim_date covering [today-3y, today+1y]."""
    start = date(date.today().year - 3, 1, 1)
    end = date(date.today().year + 1, 12, 31)
    log.info("Populating dim_date %s → %s", start, end)
    rows = []
    cur_date = start
    while cur_date <= end:
        rows.append((
            int(cur_date.strftime("%Y%m%d")),
            cur_date,
            cur_date.strftime("%A"),
            cur_date.day,
            int(cur_date.strftime("%W")) or 1,
            cur_date.month,
            cur_date.strftime("%B"),
            (cur_date.month - 1) // 3 + 1,
            cur_date.year,
            cur_date.weekday() >= 5,
            False,
            cur_date.year,
            (cur_date.month - 1) // 3 + 1,
        ))
        cur_date += timedelta(days=1)
    with conn.cursor() as c:
        c.executemany(
            "INSERT INTO dim_date (date_key, full_date, day_of_week, day_of_month, week_number, "
            "month_number, month_name, quarter, year, is_weekend, is_holiday, fiscal_year, fiscal_quarter) "
            "VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) ON CONFLICT DO NOTHING",
            rows,
        )
    conn.commit()


# (dim_table, source_oltp_table, natural_key_col, [(attr_name, source_col), ...])
DIMENSIONS = {dims_literal}

# (fact_table, source_oltp_table, date_source_col, [(dim_key, ref_dim, ref_natural_col, source_join_col), ...], [(measure, source_col), ...])
FACTS = {facts_literal}


def load_dimensions(conn) -> None:
    for dim_table, src_table, natural_col, attrs in DIMENSIONS:
        log.info("Loading %s from %s", dim_table, src_table)
        attr_csv  = ", ".join(['"natural_key"'] + [f'"{{a}}"' for a, _ in attrs])
        select_csv = ", ".join([f'CAST("{{natural_col}}" AS VARCHAR)']
                               + [f'"{{sc}}"' for _, sc in attrs])
        with conn.cursor() as c:
            c.execute(
                f'INSERT INTO "{{dim_table}}" ({{attr_csv}}) '
                f'SELECT DISTINCT {{select_csv}} FROM "{{src_table}}" '
                f'ON CONFLICT DO NOTHING'
            )
        conn.commit()


def load_facts(conn) -> None:
    for fact_table, src_table, date_col, dim_joins, measures in FACTS:
        log.info("Loading %s from %s", fact_table, src_table)
        dim_select = ", ".join(
            f'(SELECT "{{ref_dim}}_key" FROM "{{ref_dim}}" '
            f"WHERE \\"natural_key\\" = CAST(s.\\"{{join_col}}\\" AS VARCHAR) "
            f"AND is_current = TRUE LIMIT 1) AS \\"{{dim_key}}\\""
            for dim_key, ref_dim, _ref_nat, join_col in dim_joins
        )
        m_csv = ", ".join(f's."{{sc}}" AS "{{mn}}"' for mn, sc in measures)
        dim_cols = ", ".join(f'"{{dk}}"' for dk, *_ in dim_joins)
        meas_cols = ", ".join(f'"{{mn}}"' for mn, _ in measures)
        cols = '"date_key"' + (f", {{dim_cols}}" if dim_cols else "") + (f", {{meas_cols}}" if meas_cols else "")
        sel  = f'TO_CHAR(s."{{date_col}}"::date, \\'YYYYMMDD\\')::INT AS "date_key"'
        if dim_select:
            sel += f", {{dim_select}}"
        if m_csv:
            sel += f", {{m_csv}}"
        with conn.cursor() as c:
            c.execute(
                f'INSERT INTO "{{fact_table}}" ({{cols}}) '
                f'SELECT {{sel}} FROM "{{src_table}}" s'
            )
        conn.commit()


def refresh_views(conn) -> None:
    with conn.cursor() as c:
        c.execute('CALL refresh_olap_all();')
    conn.commit()


def main() -> None:
    conn = _connect()
    try:
        populate_dim_date(conn)
        load_dimensions(conn)
        load_facts(conn)
        refresh_views(conn)
        log.info("OLTP → OLAP ETL complete.")
    finally:
        conn.close()


if __name__ == "__main__":
    main()
'''


